package com.novel.agent.novel;

import lombok.Getter;

/**
 * 小说题材 (单一事实源: 前端下拉与 prompt 描述均由此枚举驱动)
 */
@Getter
public enum NovelGenre {

    /** 玄幻 */
    XUANHUAN("玄幻", "东方玄幻: 修真境界体系、宗门势力、法宝秘境, 强调成长逆袭与力量升级",
            "境界体系必须层级清晰、命名统一, 不要堆叠超过 8 个大境界; 功法/法宝的功能与代价要写清楚, 不能凭空出现或随时升级;",
            "战斗描写要具体到动作与招式效果, 不要只写\"恐怖如斯\"\"强大的力量涌出\"; 避免网文套话堆砌 (如\"眼中闪过一丝精光\"\"嘴角勾起一抹弧度\");"
    ),
    /** 仙侠 */
    XIANXIA("仙侠", "仙侠: 修仙问道、飞升因果、剑修与道法, 强调道心、宿命与逍遥",
            "道法体系要自洽, 每个法门的原理与限制要交代; 飞升/渡劫的条件要明确, 不要为了剧情随意更改规则;",
            "角色说话要符合其身份与修为, 不要人人都文绉绉满口之乎者也; 道法描写要具象, 不要只写\"一道光华闪过\";"
    ),
    /** 科幻 */
    KEHUAN("科幻", "科幻: 硬核科技或太空歌剧, 星际文明、人工智能、时间与维度, 强调设定自洽",
            "科技设定要服务于故事, 不要为了\"科幻感\"堆砌难以理解的科学名词或自创术语; 核心技术概念必须用角色能理解的日常语言自然带出, 禁止教科书式的大段原理解释; 设定要自洽但不必每个细节都有真实科学依据;",
            "对话中禁止出现大段技术独白或\"科普式\"台词; 科技名词要融入日常生活语境, 不要每个设备都先解释一遍原理; 避免\"宛如星辰大海般\"这类空泛比喻, 科技场景用具体的感官细节 (光线/声响/震动) 描写;"
    ),
    /** 推理 */
    TUILI("推理", "推理: 本格或社会派, 案件线索、诡计设计、逻辑推演与最终反转",
            "线索必须公平: 所有关键线索在谜底揭开前都要呈现给读者, 不能最后才冒出新线索; 诡计设计要可行, 不能靠巧合或超自然力量圆场;",
            "推理过程要逐步展开, 侦探不要靠\"顿悟\"或\"突然灵光一闪\"破案, 要展示推理链条; 避免角色说话像在宣读推理论文, 对话要自然带出线索分析;"
    ),
    /** 悬疑 */
    XUANYI("悬疑", "悬疑: 悬念层层递进, 心理博弈、信息差与多反转",
            "悬念要层层递进, 不要一开始就把所有底牌摊开; 反转要有伏笔支撑, 不能为了反转而反转;",
            "氛围渲染要适度, 不要每段都堆砌阴森/诡异的形容词拖慢节奏; 角色在紧张情境下的反应要真实, 不要冷静得像在分析案情;"
    ),
    /** 奇幻 */
    HUANXIANG("奇幻", "奇幻: 西式奇幻, 魔法体系、多种族与大陆政治格局",
            "魔法体系要有明确的代价与限制, 不能出现\"万能魔法\"; 多种族的文化差异要体现在社会结构与行为上, 不只靠外貌和名字区分;",
            "种族特征要体现在角色的行为习惯与思维方式上, 不要只靠尖耳朵/绿皮肤标签化; 魔法描写要写清施法过程与消耗, 不要\"一念咒就成\";"
    ),
    /** 武侠 */
    WUXIA("武侠", "武侠: 江湖恩怨、门派武学、侠义与家国情怀",
            "武学招式要具象化, 不能只有招式名称没有实际效果; 门派规矩与江湖规矩要明确, 角色行为要符合其身份;",
            "江湖对话要有江湖气, 不要太书面化; 比武场面要写出攻防节奏, 不要一招定胜负后大段心理描写;"
    ),
    /** 言情 */
    YANQING("言情", "言情: 情感线为主, 人物关系张力、误会与共同成长",
            "情感发展要有铺垫和递进, 不要一见钟情后立刻生死相许; 误会要自然产生, 不能靠\"就是不说清楚\"硬拖剧情;",
            "内心活动要克制, 不要大段心理独白分析\"我为什么喜欢他\"; 对话要生活化, 角色不要出口成章句句金句;"
    ),
    /** 历史 */
    LISHI("历史", "历史: 真实历史背景下的架空演绎, 权谋与战争",
            "历史背景要基本符合史实, 重大历史事件与人物关系不要篡改; 架空部分要与历史背景自洽, 不能出现明显的时代错置;",
            "对话要符合时代语境, 避免出现现代网络用语或现代思维方式; 权谋描写要写出信息差与博弈过程, 不要靠对手降智推进剧情;"
    ),
    /** 都市 */
    DUSHI("都市", "都市: 现代都市背景, 职场、异能或生活流, 贴近现实语境",
            "都市背景要贴近现实生活, 场景细节要真实可信; 若有异能/超自然设定, 要有明确的边界与代价, 不能万能化;",
            "对话要口语化, 符合现代都市人日常说话方式, 可以有口头禅、网络流行语 (适度); 职场场景要真实, 不要把办公室写成过家家;"
    );

    /** 页面展示名 */
    private final String label;
    /** 供 LLM 理解题材基调的说明 */
    private final String description;
    /** 题材专属的世界观设定约束 (生成世界观时注入) */
    private final String worldviewConstraints;
    /** 题材专属的正文写作约束 (每章写作时注入) */
    private final String writingConstraints;

    NovelGenre(String label, String description, String worldviewConstraints, String writingConstraints) {
        this.label = label;
        this.description = description;
        this.worldviewConstraints = worldviewConstraints;
        this.writingConstraints = writingConstraints;
    }

    /** 按 code 解析题材, 非法值回退玄幻 */
    public static NovelGenre of(String code) {
        if (code == null || code.isBlank()) {
            return XUANHUAN;
        }
        for (NovelGenre genre : values()) {
            if (genre.name().equalsIgnoreCase(code.trim())) {
                return genre;
            }
        }
        return XUANHUAN;
    }
}
